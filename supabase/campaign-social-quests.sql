-- ---------------------------------------------------------------------
-- 3. Claiming
-- ---------------------------------------------------------------------
-- Internal: approve one pending claim and give the XP (never twice).
create or replace function public.quest__approve(p_claim_id bigint, p_reviewer text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_c public.quest_claims;
  v_q public.social_quests;
begin
  select * into v_c from public.quest_claims where id = p_claim_id for update;
  if not found then
    return jsonb_build_object('status', 'not_found');
  end if;
  if v_c.status <> 'pending' then
    return jsonb_build_object('status', 'not_pending', 'current', v_c.status);
  end if;

  select * into v_q from public.social_quests where quest_key = v_c.quest_key;

  update public.quest_claims
     set status = 'approved', xp_awarded = v_q.xp, reviewed_by = p_reviewer, reviewed_at = now()
   where id = p_claim_id;

  insert into public.xp_bonuses (whatsapp_jid, group_jid, reason, source_jid, amount, bonus_day)
  values (v_c.whatsapp_jid, v_c.group_jid, 'social_quest', v_q.quest_key, v_q.xp, now()::date)
  on conflict do nothing;

  return jsonb_build_object('status', 'ok', 'jid', v_c.whatsapp_jid, 'name', v_c.display_name,
                            'xp', v_q.xp, 'title', v_q.title, 'quest_key', v_q.quest_key);
end;
$$;

create or replace function public.quest_claim(
  p_jid text,
  p_group_jid text,
  p_display_name text,
  p_quest_key text,
  p_handle text,
  p_auto boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_key text := lower(btrim(coalesce(p_quest_key, '')));
  v_q public.social_quests;
  v_existing public.quest_claims;
  v_name text := coalesce(nullif(btrim(p_display_name), ''), 'FreelanceDAO Member');
  v_handle text := left(btrim(coalesce(p_handle, '')), 80);
  v_norm text;
  v_id bigint;
  v_had boolean;
begin
  select * into v_q from public.social_quests where quest_key = v_key and active;
  if not found then
    return jsonb_build_object('status', 'unknown_quest');
  end if;

  -- "@Name", "https://x.com/Name?s=11", "Name/" all become "name"
  v_norm := lower(v_handle);
  v_norm := regexp_replace(v_norm, '\?.*$', '');
  v_norm := regexp_replace(v_norm, '/+$', '');
  v_norm := regexp_replace(v_norm, '^.*/', '');
  v_norm := regexp_replace(v_norm, '^@', '');
  if length(v_norm) < 2 or length(v_norm) > 60 then
    return jsonb_build_object('status', 'invalid_handle');
  end if;

  select * into v_existing from public.quest_claims
   where whatsapp_jid = p_jid and quest_key = v_key for update;
  v_had := found;
  if v_had and v_existing.status = 'approved' then
    return jsonb_build_object('status', 'already_approved', 'title', v_q.title);
  end if;
  if v_had and v_existing.status = 'pending' then
    return jsonb_build_object('status', 'already_pending', 'title', v_q.title);
  end if;

  if exists (select 1 from public.quest_claims
              where quest_key = v_key and handle_norm = v_norm
                and status <> 'rejected' and whatsapp_jid <> p_jid) then
    return jsonb_build_object('status', 'handle_taken');
  end if;

  begin
    if v_had then  -- a rejected claim being resubmitted
      update public.quest_claims
         set status = 'pending', handle = v_handle, handle_norm = v_norm, display_name = v_name,
             group_jid = p_group_jid, reviewed_by = null, reviewed_at = null, created_at = now()
       where id = v_existing.id
      returning id into v_id;
    else
      insert into public.quest_claims (quest_key, whatsapp_jid, group_jid, display_name, handle, handle_norm)
      values (v_key, p_jid, p_group_jid, v_name, v_handle, v_norm)
      returning id into v_id;
    end if;
  exception when unique_violation then
    return jsonb_build_object('status', 'handle_taken');
  end;

  if coalesce(p_auto, false) then
    return public.quest__approve(v_id, 'auto') || jsonb_build_object('auto', true);
  end if;

  return jsonb_build_object('status', 'pending', 'claim_id', v_id, 'xp', v_q.xp, 'title', v_q.title);
end;
$$;

-- ---------------------------------------------------------------------
-- 4. Admin review
-- ---------------------------------------------------------------------
create or replace function public.quest_review(p_claim_id bigint, p_approve boolean, p_reviewer text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_c public.quest_claims;
begin
  if coalesce(p_approve, false) then
    return public.quest__approve(p_claim_id, p_reviewer);
  end if;

  update public.quest_claims
     set status = 'rejected', reviewed_by = p_reviewer, reviewed_at = now()
   where id = p_claim_id and status = 'pending'
  returning * into v_c;

  if v_c.id is null then
    return jsonb_build_object('status', 'not_pending');
  end if;
  return jsonb_build_object('status', 'rejected', 'jid', v_c.whatsapp_jid, 'name', v_c.display_name);
end;
$$;

create or replace function public.quest_approve_all(p_group_jid text, p_reviewer text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  r record;
  v_res jsonb;
  v_count integer := 0;
  v_xp integer := 0;
begin
  for r in
    select id from public.quest_claims
    where status = 'pending' and group_jid = p_group_jid
    order by id
  loop
    v_res := public.quest__approve(r.id, p_reviewer);
    if v_res ->> 'status' = 'ok' then
      v_count := v_count + 1;
      v_xp := v_xp + (v_res ->> 'xp')::integer;
    end if;
  end loop;
  return jsonb_build_object('approved', v_count, 'total_xp', v_xp);
end;
$$;

create or replace function public.quest_pending(p_group_jid text, p_limit integer default 40)
returns table (id bigint, display_name text, quest_key text, title text, handle text, created_at timestamptz)
language sql
stable
security definer
set search_path = public
as $$
  select c.id, c.display_name, c.quest_key, q.title, c.handle, c.created_at
  from public.quest_claims c
  join public.social_quests q on q.quest_key = c.quest_key
  where c.status = 'pending' and c.group_jid = p_group_jid
  order by c.id
  limit least(greatest(coalesce(p_limit, 40), 1), 200);
$$;

-- What a member sees with !quests: every active quest plus their own claim status.
create or replace function public.quest_overview(p_jid text)
returns table (quest_key text, platform text, owner_label text, title text, url text, xp integer, status text)
language sql
stable
security definer
set search_path = public
as $$
  select q.quest_key, q.platform, q.owner_label, q.title, q.url, q.xp, c.status
  from public.social_quests q
  left join public.quest_claims c on c.quest_key = q.quest_key and c.whatsapp_jid = p_jid
  where q.active
  order by q.sort_order, q.quest_key;
$$;

-- ---------------------------------------------------------------------
-- 5. Public, read-only list for the Campaign website (links and XP only;
--    never who claimed what)
-- ---------------------------------------------------------------------
create or replace function public.campaign_social_quests()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(jsonb_agg(jsonb_build_object(
           'quest_key', quest_key, 'platform', platform, 'owner_label', owner_label,
           'title', title, 'url', url, 'xp', xp
         ) order by sort_order, quest_key), '[]'::jsonb)
  from public.social_quests
  where active;
$$;

-- ---------------------------------------------------------------------
-- 6. The referral stats screen should only count REFERRAL bonuses now that
--    other kinds of bonus XP exist.
-- ---------------------------------------------------------------------
create or replace function public.get_referral_stats(p_jid text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_me public.contestants;
  v_count int;
  v_activated int;
  v_bonus_xp int;
begin
  select * into v_me from public.contestants where whatsapp_jid = p_jid;
  if not found then
    return jsonb_build_object('registered', false);
  end if;
  select count(*), count(*) filter (where referral_activated)
    into v_count, v_activated
    from public.contestants where referred_by = p_jid and not referral_voided;
  select coalesce(sum(amount), 0) into v_bonus_xp
    from public.xp_bonuses
    where whatsapp_jid = p_jid
      and reason in ('referral_join', 'referral_activated', 'friend_top3', 'referral_left');
  return jsonb_build_object(
    'registered', true, 'referral_code', v_me.referral_code,
    'referrals', v_count, 'activated', v_activated, 'bonus_xp', v_bonus_xp
  );
end;
$$;

