-- ---------------------------------------------------------------------
-- 1. Tables
-- ---------------------------------------------------------------------
create table if not exists public.social_quests (
  quest_key   text primary key,                 -- what members type, e.g. fdao-x
  platform    text not null,                    -- x | linkedin | tiktok | facebook | discord | paragraph
  owner_label text not null,                    -- 'FreelanceDAO' or a founder's name
  title       text not null,
  url         text not null,
  xp          integer not null default 5 check (xp >= 0),
  sort_order  integer not null default 0,
  active      boolean not null default true,
  created_at  timestamptz not null default now()
);

create table if not exists public.quest_claims (
  id            bigint generated by default as identity primary key,
  quest_key     text not null references public.social_quests (quest_key) on delete cascade,
  whatsapp_jid  text not null,
  group_jid     text not null,
  display_name  text not null default 'FreelanceDAO Member',
  handle        text not null,                  -- as typed, for the admin to look up
  handle_norm   text not null,                  -- lowercased, no @ / url, used to stop one handle being reused
  status        text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  xp_awarded    integer not null default 0,
  reviewed_by   text,
  created_at    timestamptz not null default now(),
  reviewed_at   timestamptz,
  unique (whatsapp_jid, quest_key)
);

-- One social account can only back ONE person's claim per link.
create unique index if not exists quest_claims_handle_idx
  on public.quest_claims (quest_key, handle_norm) where status <> 'rejected';
create index if not exists quest_claims_status_idx on public.quest_claims (group_jid, status);

alter table public.social_quests enable row level security;
alter table public.quest_claims enable row level security;
revoke all on table public.social_quests from anon, authenticated;
revoke all on table public.quest_claims from anon, authenticated;

