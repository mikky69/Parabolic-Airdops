-- =====================================================================
-- FreelanceDAO x Parabolic: SOCIAL SIDE QUESTS
--
-- Members follow FreelanceDAO and the founders on social media, then claim
-- XP in the WhatsApp group with:   !claim <quest-code> <your handle>
-- Each link can be claimed ONCE per person, and one social handle can only
-- be used by one person per link. An admin approves claims (!approve), or
-- set QUEST_AUTO_APPROVE=1 in the bot's .env to approve instantly.
--
-- Approved XP is stored as a row in xp_bonuses (reason 'social_quest'), so it
-- shows up on the daily / overall leaderboards and the campaign website
-- with no further changes.
--
-- Run AFTER anti_cheat_upgrade.sql (and the other bot SQL files).
-- Safe to run more than once. Everything is in one transaction.
-- =====================================================================

